def set_run(run, *, bold: bool | None = None, size: int = 12):
    run.font.name = "Times New Roman"
    run._element.rPr.rFonts.set(qn("w:ascii"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:hAnsi"), "Times New Roman")
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "Times New Roman")
    run.font.size = Pt(size)
    if bold is not None:
        run.bold = bold


def para(doc: Document, text: str = "", *, bold: bool | None = None, align=None, before=0, after=6):
    p = doc.add_paragraph()
    p.paragraph_format.space_before = Pt(before)
    p.paragraph_format.space_after = Pt(after)
    p.paragraph_format.line_spacing = 1.08
    if align is not None:
        p.alignment = align
    if text:
        r = p.add_run(text)
        set_run(r, bold=bold)
    return p


def title(doc: Document, text: str):
    p = para(doc, text, bold=True, align=WD_ALIGN_PARAGRAPH.CENTER, after=8)
    for r in p.runs:
        set_run(r, bold=True, size=12)


