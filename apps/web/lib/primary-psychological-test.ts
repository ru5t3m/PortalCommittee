function withAnswerKey(question: PrimaryPsychologicalQuestion, key: Record<string, AnswerKey>): PrimaryPsychologicalQuestion {
  const answer = key[question.id];
  if (!answer) return question;
  return { ...question, correctAnswers: answer.values, answerExplanation: answer.explanation };
}

function makeChoices(count: number) {
  return Array.from({ length: count }, (_, index) => String(index + 1));
}

function visualChoiceCount(id: string, prompt: string) {
  if (visualOptionCounts[id]) return visualOptionCounts[id];
  if (prompt.includes("из четырех")) return 4;
  const maxAnswer = Math.max(...(visualAnswerKey[id]?.values ?? ["4"]).map((value) => Number(value)).filter(Number.isFinite));
  if (maxAnswer >= 7) return 8;
  return Math.max(maxAnswer, prompt.includes("лишние") || prompt.includes("лишние фигур") ? 6 : 4);
}

